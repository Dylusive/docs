// Builds the 10,000-word real-prose fixture from the public-domain text of
// "The Wind in the Willows" (Kenneth Grahame, 1908; Project Gutenberg #289).
import fs from 'node:fs'
const raw = fs.readFileSync(process.argv[2], 'utf8').replace(/\r/g, '')
const lines = raw.split('\n')
const start = lines.findIndex((l, i) => i > 50 && l.trim() === 'THE RIVER BANK')
const body = lines.slice(start).join('\n')
const paras = body.split(/\n\s*\n/).map((p) => p.replace(/\s+/g, ' ').trim()).filter(Boolean)
const out = []; let words = 0
for (const p of paras) {
  const isHead = /^[A-Z][A-Z .’'-]+$/.test(p) && p.length < 40
  if (/^[IVX]+\.$/.test(p)) continue
  if (isHead) { out.push({ h: p.replace(/^[IVX]+\.\s*/, '').replace(/\.$/, '') }); continue }
  const w = p.split(' ')
  if (words + w.length >= 10000) { out.push({ p: w.slice(0, 10000 - words).join(' ') }); words = 10000; break }
  out.push({ p }); words += w.length
}
const titled = (s) => s.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase())
const ts = `// GENERATED by scripts/gen-fixture.mjs — exactly ${words} words of real prose.
// Source: "The Wind in the Willows" by Kenneth Grahame (1908), public domain, via Project Gutenberg #289.
export interface FixtureBlock { h?: string; p?: string }
export const FIXTURE_WORDS = ${words}
export const FIXTURE: FixtureBlock[] = ${JSON.stringify(out.map((b) => (b.h ? { h: titled(b.h) } : b)), null, 0).replace(/\},\{/g, '},\n{')}
`
fs.writeFileSync(new URL('../src/lib/pagination/fixture.ts', import.meta.url), ts)
console.log('words', words, 'blocks', out.length, 'heads', out.filter((b) => b.h).map((b) => b.h))
