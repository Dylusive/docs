// Generates src/styles/fonts.generated.css + src/lib/fontFiles.generated.ts from installed @fontsource packages.
// - only families whose package licence is OFL-1.1
// - only the Latin and Latin-Extended subsets, as woff2, weights 400-700 (+ italics where the family has them)
// - every @font-face keeps its exact unicode-range, so the two subset files never overlap: without it the
//   browser mixes glyphs from both files, kerning breaks across the seam and line breaks become unstable.
import fs from 'node:fs'
import path from 'node:path'
const root = path.resolve(import.meta.dirname, '..')
const dir = path.join(root, 'node_modules/@fontsource')
const WEIGHTS = [400, 500, 600, 700]
const SUBSETS = ['latin', 'latin-ext']
const css = ['/* GENERATED by scripts/gen-fonts.mjs — do not edit. All families are SIL OFL 1.1. */']
const catalog = {}
let faces = 0
for (const pkg of fs.readdirSync(dir).sort()) {
  const lic = JSON.parse(fs.readFileSync(path.join(dir, pkg, 'package.json'), 'utf8')).license
  if (lic !== 'OFL-1.1') { console.warn('SKIP non-OFL', pkg, lic); continue }
  const weights = [], italics = []
  for (const w of WEIGHTS) for (const style of ['normal', 'italic']) {
    const file = path.join(dir, pkg, style === 'normal' ? `${w}.css` : `${w}-italic.css`)
    if (!fs.existsSync(file)) continue
    const blocks = fs.readFileSync(file, 'utf8').match(/@font-face\s*{[^}]*}/g) ?? []
    for (const subset of SUBSETS) {
      const woff2 = `${pkg}-${subset}-${w}-${style}.woff2`
      const block = blocks.find((b) => b.includes(`/${woff2}`))
      if (!block || !fs.existsSync(path.join(dir, pkg, 'files', woff2))) continue
      const family = /font-family:\s*([^;]+);/.exec(block)[1].trim()
      const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1].trim()
      if (!range) throw new Error(`no unicode-range for ${woff2}`)
      css.push(`@font-face{font-family:${family};font-style:${style};font-weight:${w};font-display:swap;src:url('../../node_modules/@fontsource/${pkg}/files/${woff2}') format('woff2');unicode-range:${range}}`)
      faces++
      if (subset === 'latin') (style === 'normal' ? weights : italics).push(w)
    }
  }
  catalog[pkg] = { weights, italics }
}
fs.writeFileSync(path.join(root, 'src/styles/fonts.generated.css'), css.join('\n') + '\n')
fs.writeFileSync(path.join(root, 'src/lib/fontFiles.generated.ts'),
  '// GENERATED by scripts/gen-fonts.mjs\nexport const FONT_FILES: Record<string, { weights: number[]; italics: number[] }> = ' + JSON.stringify(catalog, null, 1) + '\n')
console.log(Object.keys(catalog).length, 'families,', faces, '@font-face rules')
